const fs=require('fs');
const src=fs.readFileSync('qml/settings/pages/gmailfilter.js','utf8').replace('.pragma library','');
const G=new Function(src+';return {pred,ruleJson,editable,fields}')();
const eq=(a,b,m)=>{ const x=JSON.stringify(a), y=JSON.stringify(b); if(x!==y){console.error('FAIL',m,x,y);process.exit(1)} };
eq(G.pred(''),null,'empty'); eq(G.pred(' , ;'),null,'only separators');
eq(G.pred('a@x.com'),{kind:'from_addresses',value:['a@x.com']},'one address');
eq(G.pred('a@x.com, b@y.org;c@z.io'),{kind:'from_addresses',value:['a@x.com','b@y.org','c@z.io']},'several addresses');
eq(G.pred('@x.com'),{kind:'sender_contains',value:['@x.com']},'domain with @');
eq(G.pred('x.com'),{kind:'sender_contains',value:['x.com']},'bare domain');
eq(G.pred('a@x.com @y.org'),{kind:'sender_contains',value:['a@x.com','@y.org']},'mixed -> sender text, not exact');
eq(G.pred('lucia'),{kind:'sender_contains',value:['lucia']},'fragment is sent on; the backend refuses it');
eq(JSON.parse(G.ruleJson(' Family ','a@x.com','')),{name:'Gmail filter: Family',conditions:[{kind:'from_addresses',value:['a@x.com']}],exceptions:[],actions:{tags:['Family'],stop:false}},'rule, no unless');
eq(JSON.parse(G.ruleJson('F','@x.com','boss@x.com')).exceptions,[{kind:'from_addresses',value:['boss@x.com']}],'unless');
const f=(conds,excs,editable=true)=>({editable,rule:{conditions:conds,exceptions:excs,actions:{tags:['Family'],stop:false}}});
const s=(k,v)=>({kind:k,value:v});
eq(G.editable(f([s('from_addresses',['a@x.com'])],[])),true,'plain');
eq(G.editable(f([s('from_addresses',['a@x.com'])],[s('sender_contains',['@y.org'])])),true,'one unless');
eq(G.editable(f([s('from_addresses',['a@x.com']),s('recipient_contains',['me@z.com'])],[])),false,'two conditions: form cannot show it');
eq(G.editable(f([s('recipient_contains',['me@z.com'])],[])),false,'recipient only');
eq(G.editable(f([s('has_attachments',true)],[])),false,'attachment');
eq(G.editable(f([s('from_addresses',['a@x.com'])],[s('from_addresses',['a@y.com']),s('from_addresses',['b@y.com'])])),false,'two unless');
eq(G.editable(f([s('from_addresses',['a@x.com'])],[],false)),false,'read-only filter');
eq(G.editable({editable:true}),false,'no rule');
eq(G.fields(f([s('from_addresses',['a@x.com','b@y.org'])],[s('sender_contains',['@z.io'])])),{tag:'Family',from:'a@x.com, b@y.org',unless:'@z.io'},'fields');
console.log('gmailfilter ok');
