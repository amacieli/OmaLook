const fs=require('fs');
const src=fs.readFileSync('qml/keys/Search.js','utf8').replace('.pragma library','');
const S=new Function(src+';return {tokens,has,toggle,quote,stripReplyPrefix}')();
const eq=(a,b,m)=>{ const x=JSON.stringify(a), y=JSON.stringify(b); if(x!==y){console.error('FAIL',m,x,y);process.exit(1)} };
eq(S.tokens('from:bob  "two words" -x subject:"a b"'),['from:bob','"two words"','-x','subject:"a b"'],'tokens');
eq(S.tokens(''),[],'empty');
eq(S.toggle('','is:unread'),'is:unread','add to empty');
eq(S.toggle('from:bob','is:unread'),'from:bob is:unread','append');
eq(S.toggle('from:bob is:unread','is:unread'),'from:bob','remove');
eq(S.toggle('IS:UNREAD','is:unread'),'','case-insensitive remove');
eq(S.toggle('is:read from:x','is:unread'),'from:x is:unread','exclusive swap');
eq(S.toggle('subject:"a b" x','subject:"a b"'),'x','quoted term removed');
eq(S.has('a from:bob','from:bob'),true,'has');
eq(S.has('a from:bobby','from:bob'),false,'has exact');
eq(S.quote('Saint Lucia'),'"Saint Lucia"','quote');
eq(S.quote('bob@x.com'),'bob@x.com','no quote');
eq(S.quote('say "hi" now'),'"say hi now"','strip quotes');
eq(S.stripReplyPrefix('Re: RE: Fwd: Lunch'),'Lunch','strip prefixes');
eq(S.stripReplyPrefix('Report: Q3'),'Report: Q3','keeps non-prefix');
console.log('ok search');
