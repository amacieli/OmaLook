const fs=require('fs');
const src=fs.readFileSync('qml/common/links.js','utf8').replace('.pragma library','');
const X=new Function(src+';return {decide}')();
const eq=(a,b,m)=>{ const x=JSON.stringify(a), y=JSON.stringify(b); if(x!==y){console.error('FAIL',m,x,y);process.exit(1)} };
const ok=(u,o,m)=>eq(X.decide(u,o).ok,true,m+' (expected ok: '+u+')');
const no=(u,o,m)=>eq(X.decide(u,o).ok,false,m+' (expected refused: '+JSON.stringify(u)+')');
ok('https://example.com/a?b=1','https://');
ok('HTTP://Example.com','http upper-case scheme');
ok('  https://x.org  ','trimmed');
ok('Mailto:bob@x.org','mailto case-insensitive');
ok('http://127.0.0.1:27182/x','http to loopback is still http (no extra rule)');
no('tel:+1555','tel refused by default');
ok('tel:+1555',{tel:true},'tel allowed when opted in');
no('javascript:alert(1)',null,'javascript');
no('JaVaScRiPt:alert(1)',null,'javascript mixed case');
no('data:text/html,<b>x</b>',null,'data');
no('file:///etc/passwd',null,'file');
no('vbscript:msgbox(1)',null,'vbscript');
no('java\tscript:alert(1)',null,'tab inside scheme');
no('java\nscript:alert(1)',null,'newline inside scheme');
no('/relative/path',null,'no scheme');
no('',null,'empty');
no(null,null,'null');
no(undefined,null,'undefined');
no('ftp://x.org',null,'ftp');
no('zoommtg://zoom.us/join',null,'custom scheme');
console.log('ok links');
